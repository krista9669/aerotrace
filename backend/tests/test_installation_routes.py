import uuid
from datetime import UTC, datetime, timedelta
from unittest.mock import MagicMock

import pytest
from fastapi.testclient import TestClient
from sqlalchemy.exc import IntegrityError

from app.core.database import get_db
from app.main import app
from app.models import Component, Engine, Installation

INSTALLATION_ID = uuid.UUID("91b6f280-4d5d-4fa5-9a29-123456789003")
COMPONENT_ID = uuid.UUID("5487c281-4473-42b5-8fbf-4a1a3fac669c")
ENGINE_ID = uuid.UUID("1c52ee41-7c7c-4b78-a00a-c6e3c8a0a88c")

# Keep the installation timestamp safely in the past.
INSTALLED_AT = datetime(2026, 11, 14, 3, 0, tzinfo=UTC)
REMOVED_AT = datetime(2026, 11, 15, 3, 0, tzinfo=UTC)

INSTALLATION_PAYLOAD = {
    "component_id": str(COMPONENT_ID),
    "engine_id": str(ENGINE_ID),
    "installed_at": "2026-11-14T08:30:00+05:30",
    "installation_notes": "Initial installation during maintenance.",
}


@pytest.fixture
def db_session():
    return MagicMock()


@pytest.fixture
def client(db_session):
    def override_get_db():
        yield db_session

    app.dependency_overrides[get_db] = override_get_db

    with TestClient(app) as test_client:
        yield test_client

    app.dependency_overrides.pop(get_db, None)


def make_component(status="REGISTERED"):
    return Component(
        id=COMPONENT_ID,
        part_number="PN-1001",
        serial_number="SN-2026-001",
        manufacturer="Airbus",
        component_type="HYDRAULIC_PUMP",
        status=status,
        created_at=INSTALLED_AT,
    )


def make_engine():
    return Engine(
        id=ENGINE_ID,
        serial_number="ENG-2026-001",
        manufacturer="CFM International",
        model="LEAP-1A",
        aircraft_id=None,
        created_at=INSTALLED_AT,
    )


def make_installation(removed_at=None):
    return Installation(
        id=INSTALLATION_ID,
        component_id=COMPONENT_ID,
        engine_id=ENGINE_ID,
        installed_at=INSTALLED_AT,
        removed_at=removed_at,
        installation_notes="Initial installation during maintenance.",
    )


def make_integrity_error():
    return IntegrityError(
        "INSERT",
        {},
        Exception("database integrity error"),
    )


def configure_installation_creation(db_session, component=None):
    if component is None:
        component = make_component()

    component_result = MagicMock()
    component_result.first.return_value = component

    active_result = MagicMock()
    active_result.first.return_value = None

    db_session.scalars.side_effect = [
        component_result,
        active_result,
    ]

    db_session.get.return_value = make_engine()

    # Simulate values generated by the database.
    def populate_generated_fields(installation):
        installation.id = INSTALLATION_ID

    db_session.refresh.side_effect = populate_generated_fields

    return component


