def test_create_installation_returns_created_installation(client, db_session):
    configure_installation_creation(db_session)

    response = client.post(
        "/installations",
        json=INSTALLATION_PAYLOAD,
    )

    assert response.status_code == 201
    assert response.json()["id"] == str(INSTALLATION_ID)
    assert response.json()["component_id"] == str(COMPONENT_ID)
    assert response.json()["engine_id"] == str(ENGINE_ID)
    assert response.json()["removed_at"] is None

    added_installation = db_session.add.call_args.args[0]

    assert added_installation.component_id == COMPONENT_ID
    assert added_installation.engine_id == ENGINE_ID
    assert added_installation.installed_at == INSTALLED_AT

    db_session.add.assert_called_once()
    db_session.commit.assert_called_once()
    db_session.refresh.assert_called_once()


def test_create_installation_changes_component_status(client, db_session):
    component = configure_installation_creation(db_session)

    response = client.post(
        "/installations",
        json=INSTALLATION_PAYLOAD,
    )

    assert response.status_code == 201
    assert component.status == "INSTALLED"


