def test_remove_installation_records_removal_and_updates_component(client, db_session):
    installation = make_installation()
    component = make_component()

    db_session.scalars.return_value.first.return_value = installation
    db_session.get.return_value = component

    response = client.post(
        f"/installations/{INSTALLATION_ID}/remove",
        json={"removed_at": "2026-11-15T08:30:00+05:30"},
    )

    assert response.status_code == 200
    assert response.json()["id"] == str(INSTALLATION_ID)
    assert response.json()["removed_at"] is not None

    assert installation.removed_at == REMOVED_AT
    assert component.status == "REGISTERED"

    db_session.commit.assert_called_once()
    db_session.refresh.assert_called_once_with(installation)


